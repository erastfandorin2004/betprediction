// Ручная линия букмекера, введённая пользователем (он сам смотрит у БК и
// передаёт коэффициенты). Используется, когда автоматического odds-фида по
// матчу нет (товарищеские сборных не покрываются the-odds-api).

export interface ManualOdds {
  map: Record<string, number>; // для расчёта value (1X2 + тоталы голов)
  block: string;               // полный читаемый блок коэффициентов для промпта
}

function norm(s: string): string {
  return s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z]/g, '');
}

