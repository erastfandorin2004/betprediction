export function manualOddsFor(homeName: string, awayName: string): ManualOdds | null {
  const a = norm(homeName);
  const b = norm(awayName);
  return MANUAL_ODDS[`${a}|${b}`] ?? MANUAL_ODDS[`${b}|${a}`] ?? null;
}
